import { Badge } from '@/components/ui/badge';

/**
 * Honesty affordance. Every number shown anywhere in CartIQ carries one of
 * these, so a reader always knows whether they are looking at measured
 * behaviour from a public dataset or output from the session simulator.
 */
export type DataSourceKind = 'real' | 'simulated' | 'mixed' | 'demo';

const LABELS: Record<
  DataSourceKind,
  { text: string; title: string; variant: 'moss' | 'plum' | 'amber' | 'neutral' }
> = {
  real: {
    text: 'Real dataset',
    title: 'Computed from a real public e-commerce behaviour dataset.',
    variant: 'moss',
  },
  simulated: {
    text: 'Simulated',
    title:
      'Generated by the CartIQ session simulator with documented parameters. Not a real-world result. See docs/SIMULATION.md.',
    variant: 'plum',
  },
  mixed: {
    text: 'Real + simulated',
    title:
      'Combines real dataset rows with simulated sessions. Each series is labelled individually.',
    variant: 'amber',
  },
  demo: {
    text: 'Demo traffic',
    title: 'Your own clicks in this demo storefront.',
    variant: 'neutral',
  },
};

export function DataSourceBadge({ kind }: { kind: DataSourceKind }) {
  const { text, title, variant } = LABELS[kind];
  return (
    <Badge variant={variant} title={title}>
      {text}
    </Badge>
  );
}
