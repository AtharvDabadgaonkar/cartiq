"""Overview.

Phase 9 turns this into the one-screen story (top friction point → intervention
shipped → experiment result → next bet). Until the diagnosis models exist it
reports the data inventory and its provenance, which is the thing a reader has
to be able to check before trusting anything later.
"""

from __future__ import annotations

import streamlit as st

from cartiq_console.data import (
    database_available,
    dataset_imports,
    observable_steps,
    row_counts,
    simulation_runs,
)
from cartiq_console.sections import SECTIONS
from cartiq_console.theme import data_source_badge

FUNNEL = [
    "visit",
    "browse",
    "product_view",
    "add_to_cart",
    "checkout",
    "shipping",
    "payment",
    "purchase",
]

st.title("Overview")

connected = database_available()
counts: dict[str, int] = {}
if not connected:
    st.warning(
        "No database connection. Set `DATABASE_URL`, then run "
        "`make db-up && make migrate && make seed`."
    )
else:
    try:
        counts = row_counts()
    except Exception as error:  # noqa: BLE001 - surface, never crash the page
        st.warning(
            f"Schema not migrated yet ({type(error).__name__}). Run `make migrate`."
        )

total_events = counts.get("events", 0)
real = counts.get("real_events", 0)
simulated = counts.get("simulated_events", 0)

if total_events == 0:
    data_source_badge("none")
    st.info(
        "Nothing loaded yet. Run `make seed` for the committed sample, or `make ingest` "
        "for the full real dataset."
    )
else:
    data_source_badge(
        "mixed" if real and simulated else ("real" if real else "simulated")
    )

# --- Inventory -------------------------------------------------------------
st.subheader("Data inventory")
a, b, c, d = st.columns(4)
a.metric("Real events", f"{real:,}", help="Imported from a real public dataset.")
b.metric(
    "Simulated events", f"{simulated:,}", help="Generated by the session simulator."
)
c.metric("Catalog products", f"{counts.get('products', 0):,}")
d.metric(
    "Return lines", f"{counts.get('return_lines', 0):,}", help="Real cancellations."
)

if counts.get("demo_events"):
    st.caption(
        f"Plus {counts['demo_events']:,} events from clicks in the demo storefront."
    )

# --- What the real source can and cannot measure ---------------------------
if connected and real:
    try:
        steps = observable_steps()
    except Exception:  # noqa: BLE001
        steps = set()
    if steps:
        st.subheader("What the real data can measure")
        st.caption(
            "A transactional dataset records purchases, not browsing. Funnel steps it "
            "cannot observe are measured on simulated sessions instead, and labelled."
        )
        columns = st.columns(len(FUNNEL))
        for column, step in zip(columns, FUNNEL, strict=True):
            observable = step in steps
            column.markdown(
                f"{':green-badge[real]' if observable else ':violet-badge[sim]'}<br>"
                f"<span style='font-size:0.78rem'>{step.replace('_', ' ')}</span>",
                unsafe_allow_html=True,
            )

# --- Provenance ------------------------------------------------------------
if connected and total_events:
    st.subheader("Provenance")
    try:
        imports = dataset_imports()
    except Exception:  # noqa: BLE001
        imports = None
    if imports is not None and not imports.empty:
        row = imports.iloc[0]
        with st.container(border=True):
            st.markdown(f"**Real:** {row['name']}  ·  licence `{row['licence']}`")
            st.caption(row["attribution"])
            dropped = row["rows_dropped"] or {}
            if dropped:
                st.caption(
                    "Rows dropped during cleaning: "
                    + ", ".join(
                        f"{reason} {count:,}" for reason, count in dropped.items()
                    )
                )

    try:
        runs = simulation_runs()
    except Exception:  # noqa: BLE001
        runs = None
    if runs is not None and not runs.empty:
        run = runs.iloc[0]
        with st.container(border=True):
            st.markdown(
                f"**Simulated:** run `{run['label']}` · seed `{run['seed']}` · "
                f"{int(run['sessions']):,} sessions"
            )
            st.caption(
                "Behavioural assumptions, including each intervention's treatment effect, "
                "are documented in docs/SIMULATION.md and stored on this run. The "
                "Experiment Studio never reads them: it has to recover the effect from "
                "the events. Simulated figures are not real-world results."
            )

st.divider()
st.subheader("Coming sections")
for row_start in range(0, len(SECTIONS), 2):
    columns = st.columns(2)
    for column, section in zip(
        columns, SECTIONS[row_start : row_start + 2], strict=False
    ):
        if section.key == "overview":
            continue
        with column.container(border=True):
            st.markdown(
                f"**{section.label}** &nbsp; :gray-badge[Phase {section.phase}]"
            )
            st.caption(section.blurb)
