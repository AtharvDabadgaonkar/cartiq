"""Shared presentation helpers for the console.

The palette is duplicated here only as hex values for Altair; the actual UI
colours come from .streamlit/config.toml, which mirrors the storefront tokens
in apps/web/app/globals.css.
"""

from __future__ import annotations

from typing import Literal

import streamlit as st

#: Categorical ramp. Ordered so adjacent series differ in lightness as well as
#: hue, which keeps them distinguishable in the common colour-vision deficiencies.
CHART_COLORS: tuple[str, ...] = (
    "#F0A020",  # amber  — primary / signal
    "#D4654A",  # clay   — friction / drop-off
    "#7FA650",  # moss   — conversion / wins
    "#9B5F8C",  # plum
    "#C9A227",  # ochre
)

AMBER = CHART_COLORS[0]
CLAY = CHART_COLORS[1]
MOSS = CHART_COLORS[2]

DataSourceKind = Literal["real", "simulated", "mixed", "demo", "none"]

_SOURCE_LABELS: dict[str, tuple[str, str]] = {
    "real": (
        ":green-badge[Real dataset]",
        "Computed from a real public e-commerce behaviour dataset.",
    ),
    "simulated": (
        ":violet-badge[Simulated]",
        "Generated by the CartIQ session simulator with documented parameters. "
        "Not a real-world result. See docs/SIMULATION.md.",
    ),
    "mixed": (
        ":orange-badge[Real + simulated]",
        "Combines real dataset rows with simulated sessions. Each series is labelled "
        "individually.",
    ),
    "demo": (
        ":gray-badge[Demo traffic]",
        "Produced by clicks in the demo storefront.",
    ),
    "none": (
        ":gray-badge[No data loaded]",
        "Nothing has been ingested yet, so no metrics are shown.",
    ),
}


def data_source_badge(kind: DataSourceKind) -> None:
    """Render the provenance badge that must accompany every number."""
    label, help_text = _SOURCE_LABELS[kind]
    st.markdown(label, help=help_text)
